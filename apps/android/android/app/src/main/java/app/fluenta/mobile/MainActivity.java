package app.fluenta.mobile;

import android.content.Context;
import android.content.SharedPreferences;
import android.os.Bundle;
import android.webkit.WebView;
import com.getcapacitor.BridgeActivity;
import com.getcapacitor.CapConfig;
import com.getcapacitor.WebViewListener;
import java.io.BufferedReader;
import java.io.InputStream;
import java.io.InputStreamReader;
import java.nio.charset.StandardCharsets;
import org.json.JSONObject;

public class MainActivity extends BridgeActivity {

    public static final String PREFS = "fluenta_app";
    public static final String KEY_SERVER = "server_url";

    private SetupBridge setupBridge;

    @Override
    protected void onCreate(Bundle savedInstanceState) {
        String server = storedServer(this);
        if (server != null) {
            // Point the bridge at the user's server before it is created, so the
            // Capacitor runtime (and therefore the native update plugin) is
            // injected into that origin rather than the local shell.
            this.config = configForServer(server);
        }
        registerPlugin(FluentaNativePlugin.class);
        super.onCreate(savedInstanceState);

        setupBridge = new SetupBridge(this);
        getBridge().addWebViewListener(
            new WebViewListener() {
                @Override
                public void onPageLoaded(WebView webView) {
                    applySetupBridge(webView);
                }
            }
        );
        applySetupBridge(getBridge().getWebView());
    }

    /**
     * Reads the config generated by `npx cap sync` and injects the chosen server
     * URL. Using the asset config keeps every other Capacitor setting intact.
     */
    @SuppressWarnings("deprecation")
    private CapConfig configForServer(String server) {
        try (InputStream stream = getAssets().open("capacitor.config.json")) {
            StringBuilder json = new StringBuilder();
            try (BufferedReader reader = new BufferedReader(new InputStreamReader(stream, StandardCharsets.UTF_8))) {
                String line;
                while ((line = reader.readLine()) != null) json.append(line);
            }
            JSONObject root = new JSONObject(json.toString());
            JSONObject serverConfig = root.optJSONObject("server");
            if (serverConfig == null) serverConfig = new JSONObject();
            serverConfig.put("url", server);
            serverConfig.put("errorPath", "error.html");
            root.put("server", serverConfig);
            return new CapConfig(getAssets(), root);
        } catch (Exception err) {
            // Never leave the app unusable because of a malformed config asset.
            return new CapConfig.Builder(this)
                .setServerUrl(server)
                .setErrorPath("error.html")
                .setAndroidScheme("https")
                .create();
        }
    }

    /**
     * The setup interface can read and write the server address, so it must only
     * exist on pages that ship inside the APK. Remote server pages get it
     * removed before any of their scripts run.
     */
    private void applySetupBridge(WebView webView) {
        if (webView == null) return;
        String url = webView.getUrl();
        String local = getBridge().getLocalUrl();
        boolean setupMode = storedServer(this) == null;
        boolean localPage = url == null || url.isEmpty() || url.startsWith(local) || url.startsWith("file://");
        // In setup mode the whole local shell may use the bridge. Once a server
        // is configured, only the bundled error screen may — never remote content.
        boolean allow = setupMode && localPage;
        if (!setupMode && url != null && url.startsWith(local) && url.contains("error.html")) {
            allow = true;
        }
        if (allow) {
            webView.addJavascriptInterface(setupBridge, "FluentaSetup");
        } else {
            webView.removeJavascriptInterface("FluentaSetup");
        }
    }

    public static String storedServer(Context context) {
        SharedPreferences prefs = context.getSharedPreferences(PREFS, Context.MODE_PRIVATE);
        String value = prefs.getString(KEY_SERVER, null);
        if (value == null || value.trim().isEmpty()) return null;
        return value;
    }

    public static void saveServer(Context context, String url) {
        context.getSharedPreferences(PREFS, Context.MODE_PRIVATE).edit().putString(KEY_SERVER, url).apply();
    }

    public static void clearServer(Context context) {
        context.getSharedPreferences(PREFS, Context.MODE_PRIVATE).edit().remove(KEY_SERVER).apply();
    }

    public static void restart(Context context) {
        if (context instanceof MainActivity) {
            MainActivity activity = (MainActivity) context;
            activity.runOnUiThread(activity::recreate);
        }
    }
}
