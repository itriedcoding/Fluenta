type AvatarProps = {
  name: string;
  url?: string | null;
  id?: string;
  size?: number;
  presence?: Presence;
  className?: string;
};

export function Avatar({ name, url, id, size = 36, presence, className }: AvatarProps) {
  const style = { width: size, height: size, fontSize: Math.max(10, size * 0.36) };
  return (
    <span className={cx('avatar-wrap', className)} style={{ width: size, height: size }}>
      {url ? (
        <img className="avatar" style={style} src={url} alt="" loading="lazy" draggable={false} />
      ) : (
        <span className="avatar avatar-fallback" style={{ ...style, background: colorFor(id ?? name) }}>
          {initials(name)}
        </span>
      )}
      {presence && <span className={cx('presence-dot', `presence-${presence}`)} aria-label={presence} />}
    </span>
  );
}

